// Колода: карточки не повторяются, пока не закончатся все; на стыке кругов повтора тоже нет.
export function draw(seen, size, r = Math.random) {
  seen = (Array.isArray(seen) ? seen : []).filter(i => Number.isInteger(i) && i >= 0 && i < size);
  if (new Set(seen).size >= size) seen = [seen.at(-1)];
  const left = Array.from({ length: size }, (_, i) => i).filter(i => !seen.includes(i));
  const i = left[n(r, 0, left.length - 1)];
  return [i, [...seen, i]];
}
export function makeMath(last, r = Math.random) {
  let t; do t = MATH[n(r, 0, MATH.length - 1)](r); while (t[0] === last);
  return t;
}
