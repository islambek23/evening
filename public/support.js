export function ventReply(text, recent = [], r = Math.random) {
  if (crisis(text)) return SERIOUS;
  const t = text.toLowerCase(), bad = /не\s+(рада|счастл|получилось|здорово|горжусь)/.test(t);
  const theme = THEMES.find(([re], i) => re.test(t) && !(bad && i === THEMES.length - 1));
  return picker(recent, r)(theme ? theme[1] : ANY);
}
