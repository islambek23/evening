// Сначала то, чего давно не было в прошлых ответах.
function picker(recent, r) {
  return list => {
    const fresh = list.filter(t => !recent.some(x => x.includes(t)));
    const from = fresh.length ? fresh : list;
    return from[Math.floor(r() * from.length)];
  };
}
export function localReply(e, k, recent = [], r = Math.random) {
  const pick = picker(recent, r), has = t => e.tags.includes(t), out = [];
  const cause = ['conflict', 'client', 'plan', 'hard', 'nobreak'].find(has);
  const low = e.mood <= 2, hard = has('hard') || has('conflict');
  if (cause && (low || hard)) out.push(pick(OPEN[cause]));
  out.push(!low && hard ? pick(BEST) : pick(BY_MOOD[e.mood]));
  const x = ['colleague', 'sale'].find(has);
  if (x) out.push(EXTRA[x]);
  if (!low && e.fatigue >= 4) out.push(pick(TIRED));
  if (isMonthEnd(k)) out.push('Что бы ни было с планом, ты много работала.');
  return out.join(' ');
}

